#!/usr/bin/env python3
"""Emit the revision's LaTeX tables that 06 and 10 do not cover.

Reads existing artifacts only (no model weights, no GPU):
  tables/bootstrap.csv, tables/summary.csv, analysis/consensus_failures_s*/,
  analysis/pair_brown_blight_vs_tea_algal_leaf_spot_s*/summary.json.
Writes to tables/:
  bootstrap_per_seed.tex, model_complexity.tex, consensus_failures.tex,
  pair_confusion.tex, and robustness_summary.tex once tables/robustness_summary.csv
  (merged output of 08_eval_robustness.py) exists.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

from campaign import location

TABLES = location("tables_dir")
ANALYSIS = TABLES.parent / "analysis"
SEEDS = (42, 1337, 2026)
HEADER = "% generated by scripts/19_make_revision_tables.py -- do not edit by hand"

CONTRASTS = [  # (a, b, family) in the predeclared order
    ("TLA", "C1", "token"), ("C2", "C1", "token"), ("C4", "C1", "token"),
    ("TLA", "C2", "token"), ("TLA", "C4", "token"),
    ("R1", "R0", "hsv"), ("R2", "R0", "hsv"), ("R3", "R0", "hsv"),
]
LABELS = {
    "R0": "RGB baseline", "R1": "HSV sin--cos, vector gate",
    "R2": "HSV-raw, scalar gate", "R3": "HSV sin--cos, scalar gate",
    "C1": "No token module", "TLA": "Stage-4 token attention",
    "C2": "Parameter-matched MLP", "C4": "ECA comparator",
}


def pp(x: float) -> str:
    return f"{100 * x:+.2f}"


def bootstrap_table() -> list[str]:
    rows = list(csv.DictReader(open(TABLES / "bootstrap.csv", encoding="utf-8")))
    by = {(r["experiment"], r["baseline"], int(r["seed"])): r for r in rows}
    out = [HEADER, r"\begin{table*}[t]", r"\centering",
           r"\caption{Predeclared paired bootstrap comparisons, per seed. $\Delta$ is the "
           r"test Macro-F1 difference (A $-$ B) in percentage points with its pointwise 95\% "
           r"percentile interval ($B=10{,}000$ resamples of the 808 test images, one shared "
           r"index vector per replicate). Intervals are descriptive and not adjusted for "
           r"multiplicity. No interval excludes zero.}",
           r"\label{tab:bootstrap_per_seed}",
           r"\renewcommand{\arraystretch}{1.12}", r"\setlength{\tabcolsep}{4pt}",
           r"\resizebox{\textwidth}{!}{%", r"\begin{tabular}{llccccc}", r"\toprule",
           r"\textbf{Family} & \textbf{A $-$ B} & \textbf{Seed 42} & \textbf{Seed 1337} & "
           r"\textbf{Seed 2026} & \textbf{Mean $\Delta$} & \textbf{Seeds $\Delta>0$} \\",
           r"\midrule"]
    last = None
    for a, b, fam in CONTRASTS:
        if last and fam != last:
            out.append(r"\midrule")
        last = fam
        cells, ds = [], []
        for s in SEEDS:
            r = by[(a, b, s)]
            d, lo, hi = (float(r[k]) for k in ("observed_delta", "ci_low", "ci_high"))
            if r["pointwise_ci_excludes_zero"] == "True":
                raise SystemExit(f"{a}-{b} s{s}: interval excludes 0; caption must change")
            ds.append(d)
            cells.append(f"${pp(d)}$ $[{pp(lo)}, {pp(hi)}]$")
        mean = sum(ds) / len(ds)
        pos = sum(d > 0 for d in ds)
        fam_name = "Token" if fam == "token" else "HSV"
        out.append(f"{fam_name} & {a} $-$ {b} & " + " & ".join(cells)
                   + f" & ${pp(mean)}$ & {pos}/3 " + r"\\")
    out += [r"\bottomrule", r"\end{tabular}%", "}", r"\end{table*}"]
    return out


def complexity_table() -> list[str]:
    rows = {r["experiment"]: r for r in csv.DictReader(open(TABLES / "summary.csv", encoding="utf-8"))}
    out = [HEADER, r"\begin{table}[t]", r"\centering",
           r"\caption{Model complexity of the eight arms, from the completed runs. Added "
           r"parameters are relative to the family baseline (R0 or C1), which is the same "
           r"Swin-S network with the same classifier head. GFLOPs are measured with ptflops, "
           r"which omits the windowed-attention matrix products (about 2.6\% of the Swin-S "
           r"total); the omission is the same for every arm.}",
           r"\label{tab:model_complexity}",
           r"\renewcommand{\arraystretch}{1.1}", r"\begin{tabular}{llrrr}", r"\toprule",
           r"\textbf{ID} & \textbf{Configuration} & \textbf{Params (M)} & \textbf{Added params} "
           r"& \textbf{GFLOPs} \\", r"\midrule"]
    for fam, base, ids in (("hsv", "R0", ["R0", "R1", "R2", "R3"]),
                           ("token", "C1", ["C1", "TLA", "C2", "C4"])):
        if fam == "token":
            out.append(r"\midrule")
        b = float(rows[base]["params_m"])
        for i in ids:
            p = float(rows[i]["params_m"])
            added = round((p - b) * 1e6)
            add = "--" if i == base else f"{added:,}".replace(",", "{,}")
            out.append(f"{i} & {LABELS[i]} & {p:.2f} & {add} & {float(rows[i]['gflops']):.2f} " + r"\\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return out


def consensus_table() -> list[str]:
    per = {}
    for s in SEEDS:
        f = ANALYSIS / f"consensus_failures_s{s}" / f"consensus_failures_s{s}.csv"
        for r in csv.DictReader(open(f, encoding="utf-8-sig")):
            per.setdefault(r["image_id"], {})[s] = r
    common = [k for k, v in per.items() if len(v) == len(SEEDS)]
    out = [HEADER, r"\begin{table*}[t]", r"\centering",
           rf"\caption{{The {len(common)} test images misclassified by all 24 runs (8 arms "
           r"$\times$ 3 seeds). ``Same label'' means every run predicted the same wrong class. "
           r"``Review'' is the verdict of a provisional visual review of the images, which is not "
           r"independent expert ground truth; no dataset label has been changed.}",
           r"\label{tab:consensus_failures}",
           r"\renewcommand{\arraystretch}{1.1}", r"\setlength{\tabcolsep}{4pt}",
           r"\resizebox{\textwidth}{!}{%", r"\begin{tabular}{lllcl}", r"\toprule",
           r"\textbf{Image} & \textbf{Dataset label} & \textbf{Predicted (all runs)} & "
           r"\textbf{Same label} & \textbf{Review} \\", r"\midrule"]
    n_same = 0
    for k in common:
        v = per[k]
        labels = {v[s]["modal_wrong_label"] for s in SEEDS}
        same = len(labels) == 1 and all(v[s]["unanimous_same_wrong_label"] == "True" for s in SEEDS)
        n_same += same
        pred = labels.pop() if same else "mixed"
        verdicts = {v[s]["expert_label"] for s in SEEDS if v[s]["expert_label"]}
        if len(verdicts) > 1:
            raise SystemExit(f"{k}: review verdicts differ between seeds: {sorted(verdicts)}")
        verdict = verdicts.pop() if verdicts else ""
        if verdict == v[SEEDS[0]]["true_label"]:
            raise SystemExit(f"{k}: review confirms the dataset label; update the manuscript text")
        note = "Ambiguous" if verdict == "Ambiguous" else ("Suspected mislabel" if verdict else "--")
        name = k.split("/")[-1].replace("_", r"\_")
        out.append(f"\\texttt{{{name}}} & {v[SEEDS[0]]['true_label']} & {pred} & "
                   f"{'yes' if same else 'no'} & {note} " + r"\\")
    out += [r"\bottomrule", r"\end{tabular}%", "}", r"\end{table*}"]
    print(f"consensus: {len(common)} images wrong in all runs, {n_same} with the same label")
    return out


def pair_table() -> list[str]:
    arms = ["R0", "R1", "R2", "R3", "C1", "TLA", "C2", "C4"]
    counts = {a: [] for a in arms}
    for s in SEEDS:
        d = json.loads((ANALYSIS / f"pair_brown_blight_vs_tea_algal_leaf_spot_s{s}" / "summary.json").read_text())
        for r in d["Q1_pair_confusion_by_arm"]:
            counts[r["arm"]].append((r["Brown Blight -> Tea algal leaf spot"],
                                     r["Tea algal leaf spot -> Brown Blight"]))
    out = [HEADER, r"\begin{table}[t]", r"\centering",
           r"\caption{Brown Blight (BB, 86 test images) and Tea algal leaf spot (TALS, 78) "
           r"confusions per arm, summed over the three seeds.}",
           r"\label{tab:pair_confusion}", r"\begin{tabular}{lccc}", r"\toprule",
           r"\textbf{Arm} & \textbf{BB$\to$TALS} & \textbf{TALS$\to$BB} & \textbf{Total} \\",
           r"\midrule"]
    for a in arms:
        if a == "C1":
            out.append(r"\midrule")
        bt = sum(c[0] for c in counts[a]); tb = sum(c[1] for c in counts[a])
        out.append(f"{a} & {bt} & {tb} & {bt + tb} " + r"\\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return out


def robustness_table() -> list[str] | None:
    src = TABLES / "robustness_summary.csv"
    if not src.exists():
        print("robustness_summary.csv not found; robustness table skipped")
        return None
    rows = list(csv.DictReader(open(src, encoding="utf-8")))
    arms = ["R0", "R1", "R2", "R3", "C1", "TLA", "C2", "C4"]
    by = {a: [r for r in rows if r["experiment"] == a] for a in arms}
    seeds = sorted({int(r["seed"]) for r in rows})
    seed_txt = ", ".join(map(str, seeds))
    out = [HEADER, r"\begin{table*}[t]", r"\centering",
           r"\caption{Controlled perturbation robustness (Macro-F1, \%), mean $\pm$ standard "
           rf"deviation over seeds {seed_txt}. Mean and worst stress are taken over the 18 "
           r"perturbed conditions; retention is perturbed over unperturbed Macro-F1. These are "
           r"benchmark corruptions of the test images, not a measure of field generalization. "
           r"Compare arms within a family only."
           + tie_note(rows) + "}",
           r"\label{tab:robustness}", r"\renewcommand{\arraystretch}{1.1}",
           r"\begin{tabular}{lccccc}", r"\toprule",
           r"\textbf{Arm} & \textbf{Seeds} & \textbf{Unperturbed} & \textbf{Mean stress} & "
           r"\textbf{Worst stress} & \textbf{Retention} \\", r"\midrule"]

    def ms(vals: list[float]) -> str:
        m = sum(vals) / len(vals)
        sd = (sum((v - m) ** 2 for v in vals) / (len(vals) - 1)) ** 0.5 if len(vals) > 1 else 0.0
        return f"${100 * m:.2f} \\pm {100 * sd:.2f}$"

    for a in arms:
        if a == "C1":
            out.append(r"\midrule")
        g = by[a]
        if not g:
            out.append(f"{a} & 0 & -- & -- & -- & -- " + r"\\")
            continue
        cols = [ms([float(r[k]) for r in g]) for k in
                ("unperturbed", "mean_stress", "worst_stress", "mean_retention")]
        out.append(f"{a} & {len(g)} & " + " & ".join(cols) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    return out


def tie_note(rows: list[dict]) -> str:
    ties = sorted(r["run"] for r in rows if str(r.get("clean_contract", "exact")) not in ("exact", "", "nan"))
    if not ties:
        return ""
    runs = ", ".join("{} at seed {}".format(*t.rsplit("_s", 1)) for t in ties)
    return (rf" For {runs}, one test image whose stored top-2 probabilities are tied resolves to the "
            r"other class on the evaluation hardware, so the unperturbed value here is the recomputed "
            r"one and differs slightly from Table~\ref{tab:token_results}.")


GROUP_ORDER = ["brightness/contrast", "saturation", "hue shift", "white balance", "shadow",
               "gaussian noise", "blur", "jpeg compression"]
GROUP_LABEL = {"brightness/contrast": "Brightness/contrast", "saturation": "Saturation",
               "hue shift": "Hue shift", "white balance": "White balance", "shadow": "Shadow",
               "gaussian noise": "Gaussian noise", "blur": "Blur", "jpeg compression": "JPEG"}


def robustness_grouped_table() -> list[str] | None:
    src = TABLES / "robustness.csv"
    if not src.exists():
        print("robustness.csv not found; grouped robustness table skipped")
        return None
    rows = list(csv.DictReader(open(src, encoding="utf-8")))
    arms = ["R0", "R1", "R2", "R3", "C1", "TLA", "C2", "C4"]
    cell = {}
    for a in arms:
        for g in GROUP_ORDER:
            v = [float(r["macro_f1"]) for r in rows if r["experiment"] == a and r["group"] == g]
            cell[a, g] = round(100 * sum(v) / len(v), 1)  # bold is judged on the shown value
    out = [HEADER, r"\begin{table*}[t]", r"\centering",
           r"\caption{Robustness by perturbation family: test Macro-F1 (\%) averaged over the "
           r"conditions in each family and the three seeds. Within each family (row block), the "
           r"highest value is in bold (ties are all bold). The color perturbations are saturation, hue shift and "
           r"white balance.}",
           r"\label{tab:robustness_grouped}", r"\renewcommand{\arraystretch}{1.1}",
           r"\setlength{\tabcolsep}{4pt}", r"\resizebox{\textwidth}{!}{%",
           r"\begin{tabular}{l" + "c" * len(GROUP_ORDER) + "}", r"\toprule",
           r"\textbf{Arm} & " + " & ".join(rf"\textbf{{{GROUP_LABEL[g]}}}" for g in GROUP_ORDER)
           + r" \\", r"\midrule"]
    for fam in (arms[:4], arms[4:]):
        if fam[0] == "C1":
            out.append(r"\midrule")
        best = {g: max(cell[a, g] for a in fam) for g in GROUP_ORDER}
        for a in fam:
            vals = [(rf"\textbf{{{cell[a, g]:.1f}}}" if abs(cell[a, g] - best[g]) < 1e-9 else f"{cell[a, g]:.1f}")
                    for g in GROUP_ORDER]
            out.append(f"{a} & " + " & ".join(vals) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}%", "}", r"\end{table*}"]
    return out


def main() -> None:
    for name, fn in (("bootstrap_per_seed", bootstrap_table), ("model_complexity", complexity_table),
                     ("consensus_failures", consensus_table), ("pair_confusion", pair_table),
                     ("robustness_summary", robustness_table),
                     ("robustness_grouped", robustness_grouped_table)):
        lines = fn()
        if lines is None:
            continue
        p = TABLES / f"{name}.tex"
        p.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("wrote", p)


if __name__ == "__main__":
    main()
